// Command compile-peppol-schematron reproducibly compiles the pinned Peppol
// Schematron and either writes or checks the accepted executable XSLT.
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"time"

	validationassets "github.com/PaddyFrenchman/e-ubl21/validation-assets"
)

func main() {
	javaExecutable := flag.String("java", "java", "Java executable")
	saxonDir := flag.String("saxon-dir", "", "directory containing the pinned Saxon and XML Resolver JARs")
	schxsltDir := flag.String("schxslt-dir", "", "directory containing the extracted pinned SchXslt distribution")
	saxonConfig := flag.String("saxon-config", "validation-assets/saxon/saxon-config.xml", "restricted Saxon configuration")
	output := flag.String("output", "", "write the verified compiled XSLT to this path")
	check := flag.String("check", "", "compare generated bytes with this committed XSLT")
	timeout := flag.Duration("timeout", 2*time.Minute, "complete compilation and smoke-test timeout")
	flag.Parse()

	if (*output == "") == (*check == "") {
		exitf("exactly one of -output or -check is required")
	}
	ctx, cancel := context.WithTimeout(context.Background(), *timeout)
	defer cancel()
	compiled, err := validationassets.CompilePeppolSchematron(ctx, validationassets.PeppolCompilationConfig{
		JavaExecutable:         *javaExecutable,
		SaxonDirectory:         *saxonDir,
		SchXsltDirectory:       *schxsltDir,
		SaxonConfigurationPath: *saxonConfig,
	})
	if err != nil {
		exitf("%v", err)
	}

	profile := validationassets.Peppol()
	if *check != "" {
		accepted, err := os.ReadFile(filepath.Clean(*check))
		if err != nil {
			exitf("read accepted Peppol XSLT: %v", err)
		}
		if !bytes.Equal(compiled, accepted) {
			exitf("generated Peppol XSLT differs from accepted artefact %s", *check)
		}
		fmt.Printf("reproduced profile=%s version=%s compiler=%s-%s sha256=%s\n",
			profile.Name, profile.Version, validationassets.SchXslt().Name,
			validationassets.SchXslt().Version, profile.XSLTSHA256)
		return
	}

	outputPath := filepath.Clean(*output)
	outputDirectory := filepath.Dir(outputPath)
	if err := os.MkdirAll(outputDirectory, 0o755); err != nil {
		exitf("create output directory: %v", err)
	}
	temp, err := os.CreateTemp(outputDirectory, ".peppol-xslt-*")
	if err != nil {
		exitf("create temporary compiled Peppol XSLT: %v", err)
	}
	tempPath := temp.Name()
	defer os.Remove(tempPath)
	if err := temp.Chmod(0o644); err != nil {
		temp.Close()
		exitf("set compiled Peppol XSLT permissions: %v", err)
	}
	if _, err := temp.Write(compiled); err != nil {
		temp.Close()
		exitf("write temporary compiled Peppol XSLT: %v", err)
	}
	if err := temp.Close(); err != nil {
		exitf("close temporary compiled Peppol XSLT: %v", err)
	}
	if err := os.Rename(tempPath, outputPath); err != nil {
		exitf("write compiled Peppol XSLT: %v", err)
	}
	fmt.Printf("compiled profile=%s version=%s compiler=%s-%s sha256=%s output=%s\n",
		profile.Name, profile.Version, validationassets.SchXslt().Name,
		validationassets.SchXslt().Version, profile.XSLTSHA256, *output)
}

func exitf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
